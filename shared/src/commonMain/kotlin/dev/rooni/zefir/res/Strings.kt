    fun format(template: String, vararg args: Any?): String {
        var out = template
        args.forEachIndexed { i, a ->
            out = out.replace("%${i + 1}\$s", a?.toString() ?: "")
            out = out.replace("%${i + 1}\$d", (a as? Number)?.toInt()?.toString() ?: a?.toString() ?: "")
        }
        return out
    }
